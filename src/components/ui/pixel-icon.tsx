export type PixelIconName = keyof typeof glyphs;

export function PixelIcon({
  name,
  size = 16,
}: {
  name: PixelIconName;
  size?: number;
}) {
  const rows = glyphs[name];
  const top = Math.floor((16 - rows.length) / 2);
  return (
    <svg
      aria-hidden="true"
      fill="currentColor"
      height={size}
      shapeRendering="crispEdges"
      viewBox="0 0 16 16"
      width={size}
    >
      {rows.flatMap((row, y) =>
        [...row].map((cell, x) =>
          cell === "#" ? (
            <rect
              height="1"
              key={`${x}-${y}`}
              width="1"
              x={x}
              y={y + top}
            />
          ) : null,
        ),
      )}
    </svg>
  );
}
